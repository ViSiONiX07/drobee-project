"""
Bee-Brain Motor Model Module.

Implements a quadcopter motor mixer, first-order actuator response dynamics,
and approximate thrust/torque generation for four independent motors.
"""

from __future__ import annotations

from dataclasses import dataclass
import numpy as np


@dataclass
class MotorConfig:
    """Configuration constants for the motor model."""
    time_constant: float = 0.05    # Motor lag time constant in seconds
    min_speed: float = 0.0         # Minimum normalized speed [0.0, 1.0]
    max_speed: float = 1.0         # Maximum normalized speed [0.0, 1.0]
    max_thrust: float = 5.0        # Max thrust per motor in Newtons
    thrust_coefficient: float = 1.0 # Scaling factor for thrust conversion
    torque_coefficient: float = 0.05 # Scaling factor for yaw torque conversion


class MotorModel:
    """Manages four individual motors with response delays and mixer logic."""

    def __init__(self, config: MotorConfig | None = None) -> None:
        self.config = config or MotorConfig()
        # Current actual motor speeds [motor_0, motor_1, motor_2, motor_3] (normalized [0, 1])
        self.motor_speeds = np.zeros(4, dtype=float)
        # Target motor speeds commanded by mixer
        self._target_speeds = np.zeros(4, dtype=float)

    def set_commands(self, throttle: float, roll: float, pitch: float, yaw: float) -> None:
        """
        Mixes standard quadcopter control inputs (throttle, roll, pitch, yaw)
        into individual motor commands (X-configuration layout).

        Layout:
        0: Front-Right (CW)
        1: Rear-Right (CCW)
        2: Rear-Left (CW)
        3: Front-Left (CCW)
        """
        m0 = throttle - roll - pitch - yaw
        m1 = throttle - roll + pitch + yaw
        m2 = throttle + roll + pitch - yaw
        m3 = throttle + roll - pitch + yaw

        mixed = np.array([m0, m1, m2, m3], dtype=float)

        # Clamp targets to allowed speed bounds
        self._target_speeds = np.clip(
            mixed,
            self.config.min_speed,
            self.config.max_speed
        )

    def set_motor_speeds_direct(self, speeds: list[float] | np.ndarray) -> None:
        """Directly set target speeds for all 4 motors."""
        self._target_speeds = np.clip(
            np.array(speeds, dtype=float),
            self.config.min_speed,
            self.config.max_speed
        )

    def step(self, dt: float) -> np.ndarray:
        """
        Advances motor response dynamics by dt using a first-order lag filter.
        Returns the updated actual motor speeds.
        """
        if dt <= 0.0:
            raise ValueError(f"dt must be positive, got {dt}")

        alpha = dt / (self.config.time_constant + dt) if self.config.time_constant > 0 else 1.0
        self.motor_speeds += alpha * (self._target_speeds - self.motor_speeds)

        return self.motor_speeds

    def get_total_thrust(self) -> float:
        """Calculates total vertical thrust generated by all four motors."""
        thrusts = self.motor_speeds * self.config.max_thrust * self.config.thrust_coefficient
        return float(np.sum(thrusts))

    def get_yaw_torque(self) -> float:
        """Calculates net yaw torque from differential motor rotations (CW vs CCW)."""
        torque_factors = np.array([-1.0, 1.0, -1.0, 1.0], dtype=float)
        torques = self.motor_speeds * self.config.torque_coefficient * torque_factors
        return float(np.sum(torques))

    def reset(self) -> None:
        """Reset all motor speeds to zero."""
        self.motor_speeds[:] = 0.0
        self._target_speeds[:] = 0.0